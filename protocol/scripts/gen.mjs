#!/usr/bin/env node
// Generates the wire types for both sides from protocol/messages.json:
//   server/internal/protocol/protocol_gen.go   (Go structs + constants)
//   client/src/net/protocol.gen.ts             (TypeScript interfaces + unions)
//   node scripts/gen.mjs           write the files
//   node scripts/gen.mjs --check   fail if either file is out of date (used by `pnpm test`)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const schema = JSON.parse(readFileSync(resolve(root, "protocol/messages.json"), "utf8"));
const goTarget = resolve(root, "server/internal/protocol/protocol_gen.go");
const tsTarget = resolve(root, "client/src/net/protocol.gen.ts");

const BASIC = { u8: ["uint8", "number"], u16: ["uint16", "number"], u32: ["uint32", "number"], f64: ["float64", "number"], bool: ["bool", "boolean"], string: ["string", "string"] };

const field = (spec) => (typeof spec === "string" ? { type: spec } : spec);
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const ACRONYMS = new Set(["id", "vx", "vy", "vz", "ads"]);
const goName = (s) =>
  s
    .replace(/([A-Z])/g, " $1")
    .split(" ")
    .filter(Boolean)
    .map((w) => (ACRONYMS.has(w.toLowerCase()) ? w.toUpperCase() : pascal(w)))
    .join("");

function goType(t) {
  if (t.startsWith("[")) return `[]${goType(t.slice(1, -1))}`;
  return BASIC[t] ? BASIC[t][0] : t;
}
function tsType(t) {
  if (t.startsWith("[")) return `${tsType(t.slice(1, -1))}[]`;
  return BASIC[t] ? BASIC[t][1] : t;
}
const goDoc = (doc, indent = "") => (doc ? `${indent}// ${doc}\n` : "");
const tsDoc = (doc, indent = "") => (doc ? `${indent}/** ${doc} */\n` : "");

function genGo() {
  const out = [];
  out.push("// Code generated by protocol/scripts/gen.mjs from protocol/messages.json. DO NOT EDIT.");
  out.push("// Edit protocol/messages.json and run `pnpm gen`.\n");
  out.push("package protocol\n");

  out.push("// Message type names (the \"type\" field on every message).");
  out.push("const (");
  for (const name of Object.keys(schema.client)) out.push(`\tClientType${pascal(name)} = ${JSON.stringify(name)}`);
  for (const name of Object.keys(schema.server)) out.push(`\tServerType${pascal(name)} = ${JSON.stringify(name)}`);
  out.push(")\n");

  for (const [name, flags] of Object.entries(schema.flags ?? {})) {
    out.push(`// ${name} bits.`);
    out.push("const (");
    // The smallest unsigned type that holds every bit (it must match the field that carries them).
    const goType = Math.max(...Object.values(flags)) > 255 ? "uint16" : "uint8";
    for (const [flag, bit] of Object.entries(flags)) out.push(`\t${pascal(name.replace(/s$/, ""))}${pascal(flag)} ${goType} = ${bit}`);
    out.push(")\n");
  }

  const struct = (name, doc, fields, extra = []) => {
    out.push(goDoc(doc ? `${name}: ${doc}` : name).trimEnd());
    out.push(`type ${name} struct {`);
    for (const line of extra) out.push(line);
    for (const [fname, spec] of Object.entries(fields)) {
      const f = field(spec);
      if (f.doc) out.push(goDoc(f.doc, "\t").trimEnd());
      out.push(`\t${goName(fname)} ${goType(f.type)} \`json:"${fname}"\``);
    }
    out.push("}\n");
  };

  for (const [name, s] of Object.entries(schema.structs)) struct(name, s.doc, s.fields);
  for (const [name, m] of Object.entries(schema.server)) {
    struct(pascal(name), m.doc, m.fields, [`\tType string \`json:"type"\``]);
  }

  // Client messages decode into one flat struct: field names are unique across messages.
  const seen = new Map();
  const merged = {};
  for (const [name, m] of Object.entries(schema.client)) {
    for (const [fname, spec] of Object.entries(m.fields)) {
      if (seen.has(fname)) throw new Error(`client field ${fname} is used by both ${seen.get(fname)} and ${name}`);
      seen.set(fname, name);
      merged[fname] = field(spec);
    }
  }
  out.push("// ClientMessage is any client-to-server message; Type says which fields are meaningful.");
  out.push("type ClientMessage struct {");
  out.push('\tType string `json:"type"`');
  for (const [fname, f] of Object.entries(merged)) {
    out.push(`\t${goName(fname)} ${goType(f.type)} \`json:"${fname},omitempty"\``);
  }
  out.push("}\n");
  return out.join("\n");
}

function genTs() {
  const out = [];
  out.push("// Code generated by protocol/scripts/gen.mjs from protocol/messages.json. DO NOT EDIT.");
  out.push("// Edit protocol/messages.json and run `pnpm gen`.\n");

  for (const [name, flags] of Object.entries(schema.flags ?? {})) {
    out.push(`/** ${name} bits. */`);
    out.push(`export const ${name} = {`);
    for (const [flag, bit] of Object.entries(flags)) out.push(`  ${flag}: ${bit},`);
    out.push("} as const;\n");
  }

  const iface = (name, doc, fields, extra = []) => {
    out.push(tsDoc(doc).trimEnd() || `/** ${name} */`);
    out.push(`export interface ${name} {`);
    for (const line of extra) out.push(line);
    for (const [fname, spec] of Object.entries(fields)) {
      const f = field(spec);
      if (f.doc) out.push(tsDoc(f.doc, "  ").trimEnd());
      out.push(`  ${fname}: ${tsType(f.type)};`);
    }
    out.push("}\n");
  };

  for (const [name, s] of Object.entries(schema.structs)) iface(name, s.doc, s.fields);
  const msgIface = (side) => (name, m) => iface(`${pascal(name)}${side}`, m.doc, m.fields, [`  type: ${JSON.stringify(name)};`]);
  for (const [name, m] of Object.entries(schema.client)) msgIface("Message")(name, m);
  for (const [name, m] of Object.entries(schema.server)) msgIface("Message")(name, m);

  const union = (alias, side) =>
    `export type ${alias} =\n${Object.keys(schema[side])
      .map((n) => `  | ${pascal(n)}Message`)
      .join("\n")};\n`;
  out.push(union("ClientMessage", "client"));
  out.push(union("ServerMessage", "server"));
  out.push(`const SERVER_TYPES = new Set<string>(${JSON.stringify(Object.keys(schema.server))});\n`);

  // Binary frames carry every struct as an array of its fields in declaration order (no field
  // names on the wire). The layouts below are that order; the Go side gets it from its structs.
  const layoutOf = (fields, typed) => [
    ...(typed ? [["type", "string"]] : []),
    ...Object.entries(fields).map(([fname, spec]) => [fname, field(spec).type]),
  ];
  const layouts = {};
  for (const [name, s] of Object.entries(schema.structs)) layouts[name] = layoutOf(s.fields, false);
  for (const [name, m] of Object.entries(schema.server)) layouts[`server:${name}`] = layoutOf(m.fields, true);
  // Client messages are one flat struct on the server: the type, then every message's fields.
  layouts.client = [["type", "string"], ...Object.values(schema.client).flatMap((m) => layoutOf(m.fields, false))];
  out.push("/** Field order of every struct and message, as binary frames carry them (arrays, no field names). */");
  out.push(`const LAYOUTS: Record<string, readonly (readonly [string, string])[]> = ${JSON.stringify(layouts)};\n`);
  out.push(`function unpack(type: string, value: unknown): unknown {
  if (type.startsWith("[")) {
    const inner = type.slice(1, -1);
    return Array.isArray(value) ? value.map((v) => unpack(inner, v)) : [];
  }
  const layout = LAYOUTS[type];
  if (!layout) return value;
  const items = Array.isArray(value) ? (value as unknown[]) : [];
  const out: Record<string, unknown> = {};
  layout.forEach(([name, t], i) => {
    out[name] = unpack(t, items[i]);
  });
  return out;
}

function pack(type: string, value: unknown): unknown {
  if (type.startsWith("[")) {
    const inner = type.slice(1, -1);
    return Array.isArray(value) ? value.map((v) => pack(inner, v)) : [];
  }
  const layout = LAYOUTS[type];
  if (!layout) return value ?? (type === "string" ? "" : type === "bool" ? false : 0);
  const fields = (value ?? {}) as Record<string, unknown>;
  return layout.map(([name, t]) => pack(t, fields[name]));
}

/** Decode a binary frame's value (the decoded MessagePack array) into a server message, or null. */
export function unpackServerMessage(value: unknown): ServerMessage | null {
  if (!Array.isArray(value)) return null;
  const type: unknown = value[0];
  if (typeof type !== "string" || !SERVER_TYPES.has(type)) return null;
  return unpack(\`server:\${type}\`, value) as ServerMessage;
}

/** A client message as the array a binary frame carries (encode it with MessagePack). */
export function packClientMessage(msg: ClientMessage): unknown[] {
  return pack("client", msg) as unknown[];
}
`);
  out.push("/** Parse a server message. Returns null for anything that is not a known message. */");
  out.push("export function parseServerMessage(text: string): ServerMessage | null {");
  out.push("  const msg = JSON.parse(text) as { type?: unknown };");
  out.push('  return typeof msg.type === "string" && SERVER_TYPES.has(msg.type) ? (msg as ServerMessage) : null;');
  out.push("}");
  return `${out.join("\n")}\n`;
}

const goSource = execFileSync("gofmt", [], { input: genGo(), encoding: "utf8" });
const tsSource = genTs();

if (process.argv.includes("--check")) {
  const read = (p) => {
    try {
      return readFileSync(p, "utf8");
    } catch {
      return "";
    }
  };
  const stale = [];
  if (read(goTarget) !== goSource) stale.push(goTarget);
  if (read(tsTarget) !== tsSource) stale.push(tsTarget);
  if (stale.length > 0) {
    console.error(`generated protocol files are out of date:\n  ${stale.join("\n  ")}\nRun: pnpm gen`);
    process.exit(1);
  }
  console.log("protocol files are up to date");
} else {
  writeFileSync(goTarget, goSource);
  writeFileSync(tsTarget, tsSource);
  console.log(`wrote ${goTarget}\nwrote ${tsTarget}`);
}
