#!/usr/bin/env node
// Generates server/internal/game/params_gen.go from shared/params.json.
//   node scripts/gen-go.mjs           write the file
//   node scripts/gen-go.mjs --check   fail if the file is out of date (used by `pnpm test`)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const source = resolve(root, "shared/params.json");
const target = resolve(root, "server/internal/game/params_gen.go");

const params = JSON.parse(readFileSync(source, "utf8"));

const pascal = (s) => s[0].toUpperCase() + s.slice(1);

/** Untyped Go constants are used so they mix freely with float64 and int. */
function emit(prefix, section) {
  const consts = [];
  const vars = [];
  for (const [key, value] of Object.entries(section)) {
    const name = prefix + pascal(key);
    if (Array.isArray(value)) {
      vars.push(`var ${name} = [...]float64{${value.map(String).join(", ")}}`);
    } else if (typeof value === "number") {
      consts.push(`\t${name} = ${String(value)}`);
    } else {
      throw new Error(`unsupported value for ${key}: ${JSON.stringify(value)}`);
    }
  }
  return `const (\n${consts.join("\n")}\n)\n\n${vars.join("\n")}\n`;
}

const raw = `// Code generated by shared/scripts/gen-go.mjs from shared/params.json. DO NOT EDIT.
// Edit shared/params.json and run \`pnpm gen\`.

package game

// Movement tuning (shared/params.json "movement").
${emit("", params.movement)}
// Weapon tuning (shared/params.json "weapon"), prefixed with Weapon.
${emit("Weapon", params.weapon)}
// Sniper tuning (shared/params.json "sniper"), prefixed with Sniper.
${emit("Sniper", params.sniper)}
// Combat tuning (shared/params.json "combat"), prefixed with Combat.
${emit("Combat", params.combat)}
// Match flow (shared/params.json "match"), prefixed with Match.
${emit("Match", params.match)}
// Thunder spear launcher tuning (shared/params.json "spear"), prefixed with Spear.
${emit("Spear", params.spear)}
// Hero skills (shared/params.json "skill"), prefixed with Skill.
${emit("Skill", params.skill)}`;

const formatted = execFileSync("gofmt", [], { input: raw, encoding: "utf8" });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file counts as out of date
  }
  if (current !== formatted) {
    console.error("server/internal/game/params_gen.go is out of date with shared/params.json. Run: pnpm gen");
    process.exit(1);
  }
  console.log("params_gen.go is up to date");
} else {
  writeFileSync(target, formatted);
  console.log(`wrote ${target}`);
}
